export function parseCommand(value) {
  const m = /^\/(\w+)(?:\s+([\s\S]*))?$/u.exec(value.trim());
  if (!m) return null;
  const entry = commands.find(([key]) => key === m[1].toLowerCase());
  return entry ? { key: entry[0], instruction: entry[2], argument: m[2]?.trim() || '' } : null;
}
